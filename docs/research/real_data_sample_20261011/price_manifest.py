#!/usr/bin/env python3
"""Manifest (hashes + row counts) for the daily price CSVs produced by max_prices.py.
The CSVs themselves are raw market data and are NOT tracked in Git (AGENTS.md rule 6); they are
regenerated into the untracked _out/ directory by run_all.sh.

  python price_manifest.py --write DIR     # write price_manifest.json from DIR/daily_*.csv
  python price_manifest.py --check DIR     # exit 1 unless DIR/daily_*.csv match the manifest exactly
"""
import hashlib, json, pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
TICKERS = ("AAPL", "JNJ", "ADBE")


def describe(path):
    b = pathlib.Path(path).read_bytes()
    lines = b.decode().splitlines()
    body = [l.split(",") for l in lines[1:]]
    return dict(sha256=hashlib.sha256(b).hexdigest(), rows=len(body), first_date=body[0][0], last_date=body[-1][0],
                columns=lines[0],
                raw_close_sha256=hashlib.sha256("".join(f"{r[0]},{r[1]}\n" for r in body).encode()).hexdigest())


def main():
    mode, d = sys.argv[1], pathlib.Path(sys.argv[2])
    cur = {f"daily_{t}.csv": describe(d / f"daily_{t}.csv") for t in TICKERS}
    if mode == "--write":
        old = json.load(open(HERE / "price_manifest.json")) if (HERE / "price_manifest.json").exists() else {}
        out = dict(note="Manifest of the originally used daily price CSVs (not tracked in Git: AGENTS.md rule 6). "
                        "Regenerated by max_prices.py into _out/ (untracked). Yahoo adjusted close is vendor-revisable; "
                        "raw_close_sha256 covers date+raw close only.",
                   window="2026-07-01..2026-10-09", generated_by="max_prices.py (daily_<T>.csv)", files=cur)
        out.update({k: v for k, v in old.items() if k not in out})
        (HERE / "price_manifest.json").write_text(json.dumps(out, indent=1) + "\n")
        return 0
    man = json.load(open(HERE / "price_manifest.json"))["files"]
    bad = [k for k in cur if cur[k] != man[k]]
    for k in cur:
        print(k, "MATCH" if k not in bad else "DIFFERS")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
